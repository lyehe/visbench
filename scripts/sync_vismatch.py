"""Keep the vendored vismatch in ``third_party/vismatch`` in sync with its fork.

vismatch is vendored here as a squashed ``git subtree``. Its development happens in a separate fork
checkout, which also merges new features from upstream gmberton/vismatch (see that repo's
``scripts/sync_upstream.py``). This script pulls the fork's branch into visbench and regenerates the
root ``.gitmodules`` entries for vismatch's third-party model submodules (git only reads the
top-level ``.gitmodules``, so vismatch's own file is not enough once it is vendored).

Usage (from the visbench root, with a clean working tree)::

    uv run python scripts/sync_vismatch.py --fork ../featurexx/third_party/vismatch   # pull + regenerate
    uv run python scripts/sync_vismatch.py --gitmodules-only                          # regenerate only

Then initialise whichever model submodules you need, e.g.
``git submodule update --init third_party/vismatch/vismatch/third_party/LoMa``.
"""

from __future__ import annotations

import argparse
import configparser
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PREFIX = "third_party/vismatch"
BEGIN = "# >>> vendored vismatch submodules (generated by scripts/sync_vismatch.py; do not edit) >>>"
END = "# <<< vendored vismatch submodules <<<"


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, check=True, capture_output=True, text=True).stdout


def vendored_submodules() -> list[tuple[str, str]]:
    """(path relative to visbench root, url) for every submodule declared by the vendored vismatch."""
    parser = configparser.ConfigParser(interpolation=None)
    parser.read_string((ROOT / PREFIX / ".gitmodules").read_text(encoding="utf-8"))
    return sorted((f"{PREFIX}/{parser[s]['path']}", parser[s]["url"]) for s in parser.sections())


def regenerate_gitmodules() -> int:
    path = ROOT / ".gitmodules"
    text = path.read_text(encoding="utf-8") if path.exists() else ""
    text = re.sub(rf"\n?{re.escape(BEGIN)}.*?{re.escape(END)}\n?", "\n", text, flags=re.S).strip("\n")
    entries = vendored_submodules()
    block = "\n".join(f'[submodule "{p}"]\n\tpath = {p}\n\turl = {u}' for p, u in entries)
    new = (text + "\n\n" if text else "") + f"{BEGIN}\n{block}\n{END}\n"
    path.write_text(new, encoding="utf-8", newline="\n")
    tracked = {line.split("\t")[1] for line in git("ls-files", "-s", PREFIX).splitlines() if line.startswith("160000")}
    missing = sorted({p for p, _ in entries} - tracked)
    if missing:
        print(f"warning: declared but not committed as submodules: {missing}", file=sys.stderr)
    print(f"{len(entries)} vismatch submodules registered in .gitmodules")
    return 0


def pull(fork: str, branch: str) -> int:
    if git("status", "--porcelain", "--untracked-files=no").strip():
        sys.exit("working tree has uncommitted changes; commit or stash them first")
    subprocess.run(["git", "subtree", "pull", "--prefix", PREFIX, "--squash", fork, branch], cwd=ROOT, check=True)
    regenerate_gitmodules()
    if git("status", "--porcelain", "--", ".gitmodules").strip():
        git("add", ".gitmodules")
        git("commit", "-m", "chore: refresh vendored vismatch submodule entries")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--fork", help="path or URL of the vismatch fork to pull from")
    ap.add_argument("--branch", default="main", help="fork branch to pull (default: main)")
    ap.add_argument("--gitmodules-only", action="store_true", help="only regenerate .gitmodules")
    args = ap.parse_args()
    if args.gitmodules_only:
        return regenerate_gitmodules()
    if not args.fork:
        ap.error("--fork is required unless --gitmodules-only is given")
    return pull(args.fork, args.branch)


if __name__ == "__main__":
    raise SystemExit(main())
